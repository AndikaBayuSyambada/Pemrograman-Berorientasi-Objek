    private void btnBagiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBagiActionPerformed
        // TODO add your handling code here:
        double[] input = validasiDanAmbilInput(true);
        if (input != null) {
        // Validasi pembagian dengan nol
        if (input[1] == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Tidak dapat membagi dengan angka nol!", "Error Arithmetic", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        double hasil = input[0] / input[1];
        txhasil.setText(String.valueOf(hasil));
        }
    }//GEN-LAST:event_btnBagiActionPerformed

