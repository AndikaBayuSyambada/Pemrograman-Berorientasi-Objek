// Method pembantu untuk mengecek input kosong dan format angka
private double[] validasiDanAmbilInput(boolean butuhInput2) {
    String str1 = txnilai1.getText().trim();
    String str2 = txnilai2.getText().trim();

    // 1. Cek Apakah Input Kosong
    if (str1.isEmpty() || (butuhInput2 && str2.isEmpty())) {
        javax.swing.JOptionPane.showMessageDialog(this, "Inputan msh kosong", "Message", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        return null; // Mengembalikan null sebagai tanda validasi gagal
    }

    try {
        // 2. Cek Apakah Format Angka Valid (Mencegah Error Huruf)
        double n1 = Double.parseDouble(str1);
        double n2 = butuhInput2 ? Double.parseDouble(str2) : 0;
        return new double[]{n1, n2};
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Masukkan format angka yang valid!", "Error Input", javax.swing.JOptionPane.ERROR_MESSAGE);
        return null;
    }
}
