    private void btnOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOkActionPerformed
        String mysqldumpPath = getMysqldumpPath();
        // Menggunakan array String agar spasi pada nama folder diproses dengan benar oleh OS
        String[] executeCmd = {
            mysqldumpPath,
            "-uroot",
            "penjualan",
            "-r",
            "E:\\Andika Bayu\\KULIAH\\TUGAS KULIAH\\Semester 4\\PEMROGRAMAN BERORIENTASI OBJEK\\Pratikum\\Praktikum 11\\bckpenjual.sql"
        };
        
        try {
            Process runtime = Runtime.getRuntime().exec(executeCmd);
            try {
                int prosescomplete = runtime.waitFor();
                if (prosescomplete == 0) {
                    JOptionPane.showMessageDialog(rootPane, "Backup sukses!");
                } else {
                    JOptionPane.showMessageDialog(rootPane, "Backup gagal!");
                }
            } catch (InterruptedException ex) {
                Logger.getLogger(frmBackupDatabase.class.getName()).log(Level.SEVERE, null, ex);
            }
        } catch (IOException ex) {
            Logger.getLogger(frmBackupDatabase.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnOkActionPerformed

