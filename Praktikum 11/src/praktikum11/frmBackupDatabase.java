    /**
     * Method untuk mencari path executable mysqldump secara otomatis di komputer.
     * Ini memastikan program berjalan baik di XAMPP, Laragon, maupun instalasi MySQL standar.
     */
    private String getMysqldumpPath() {
        String[] paths = {
            "D:/laragon/bin/mysql/mysql-8.0.30-winx64/bin/mysqldump.exe",
            "C:/xampp/mysql/bin/mysqldump.exe",
            "C:/Program Files/MySQL/MySQL Server 8.0/bin/mysqldump.exe",
            "C:/Program Files/MySQL/MySQL Server 5.7/bin/mysqldump.exe",
            "C:/Program Files/MySQL/MySQL Server 5.6/bin/mysqldump.exe",
            "C:/Program Files/MySQL/MySQL Server 5.5/bin/mysqldump.exe",
            "C:/Program Files/MySQL/MySQL Server 5.0/bin/mysqldump.exe",
            "mysqldump" // Fallback ke sistem PATH
        };
        for (String path : paths) {
            if (path.equals("mysqldump")) {
                return path;
            }
            java.io.File file = new java.io.File(path);
            if (file.exists()) {
                return path;
            }
        }
        return "mysqldump";
    }

