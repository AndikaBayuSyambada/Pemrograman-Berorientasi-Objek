    // Method baca data dari Mysql dimasukkan ke jTable1
    private void baca_data() {
    try {
        stm = Con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        RsBrg = stm.executeQuery("select * from barang");
        ResultSetMetaData meta = RsBrg.getMetaData();
        int col = meta.getColumnCount();
        int baris = 0;
        while (RsBrg.next()) {
            baris = RsBrg.getRow();
        }
        dataTable = new Object[baris][col];
        int x = 0;
        RsBrg.beforeFirst();
        while (RsBrg.next()) {
            dataTable[x][0] = RsBrg.getString("kd_brg");
            dataTable[x][1] = RsBrg.getString("nm_brg");
            dataTable[x][2] = RsBrg.getString("satuan");
            dataTable[x][3] = RsBrg.getDouble("harga_beli"); // Kolom baru (indeks 3)
            dataTable[x][4] = RsBrg.getDouble("harga_jual"); // Bergeser ke indeks 4
            dataTable[x][5] = RsBrg.getInt("stok");          // Bergeser ke indeks 5
            dataTable[x][6] = RsBrg.getInt("stok_min");      // Bergeser ke indeks 6
            x++;
        }
        tbl_barang.setModel(new DefaultTableModel(dataTable, header));
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, e);
    }
    }

