    private void btn_simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_simpanActionPerformed
        // TODO add your handling code here:
        String tKode = txt_kodebarang.getText();
        String tNama = txt_namabarang.getText();
        String tSatuan = (String) cb_satuan.getSelectedItem();
    
        // Membaca input harga beli baru
        double hrgBeli = Double.parseDouble(txt_hargabeli.getText()); 
        double hrgJual = Double.parseDouble(txt_hargajual.getText());
        int stk = Integer.parseInt(txt_stok.getText());
        int stkMin = Integer.parseInt(txt_stokminimal.getText());
        
        try {
            if (edit == true) {
            // Query UPDATE disesuaikan dengan field harga_beli dan harga_jual
            stm.executeUpdate("UPDATE barang SET nm_brg='" + tNama + "', satuan='" + tSatuan + 
                              "', harga_beli=" + hrgBeli + ", harga_jual=" + hrgJual + 
                              ", stok=" + stk + ", stok_min=" + stkMin + 
                              " WHERE kd_brg='" + tKode + "'");
            } else {
            // Query INSERT disesuaikan dengan field harga_beli dan harga_jual
            stm.executeUpdate("INSERT INTO barang (kd_brg, nm_brg, satuan, harga_beli, harga_jual, stok, stok_min) VALUES('" 
                              + tKode + "', '" + tNama + "', '" + tSatuan + "', " + hrgBeli + ", " + hrgJual + ", " + stk + ", " + stkMin + ")");
            }
            
            baca_data();
            aktif(false);
            setTombol(true);
            edit = false;
            JOptionPane.showMessageDialog(null, "Data barang berhasil disimpan!");
        
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Gagal menyimpan data: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_simpanActionPerformed

